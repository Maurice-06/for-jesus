export function parseReference(input) {
  if (!input?.trim()) return null
  const s = input.trim()
  // Match: (optional number + space) + book name(s) + space + chapter(:verse)?
  const m = s.match(/^(\d\s+)?(.+?)\s+(\d+)(?::(\d+))?$/i)
  if (!m) return null

  const prefix = m[1] ? m[1].trim() : ''
  const rawBook = m[2].trim().toLowerCase()
    .normalize('NFD').replace(/[\u0300-\u036f]/g, '') // strip accents for matching
  const chapter = parseInt(m[3])
  const verse = m[4] ? parseInt(m[4]) : null

  // Try with and without accent normalization
  const lookup = (key) => {
    const norm = key.normalize('NFD').replace(/[\u0300-\u036f]/g, '')
    for (const [k, v] of Object.entries(FRENCH_BOOK_MAP)) {
      const kNorm = k.normalize('NFD').replace(/[\u0300-\u036f]/g, '')
      if (kNorm === norm) return v
    }
    return null
  }

  const fullKey = prefix ? `${prefix} ${rawBook}` : rawBook
  const bookId = lookup(fullKey) || lookup(rawBook)
  const book = ALL_BOOKS.find(b => b.id === bookId)
  if (!book) return null
  if (chapter < 1 || chapter > book.chapters) return null
  return { book, chapter, verse: verse || null }
}

